import * as fs from "fs";
import * as os from "os";
import * as path from "path";
import { replaceFile } from "../core/fs-utils";

/** The launcher's file name marks AgentPool's entries in Claude Code's settings. */
const TAG = "agent-pool-handoff";

export function hooksDir(): string {
  const home = process.env.AGENT_POOL_HOME || path.join(os.homedir(), ".agent-pool");
  return path.join(home, "hooks");
}

/**
 * Copies the hook script to a stable place (the extension folder changes on every update)
 * and writes a launcher: `node` when the person has it, else VS Code's own runtime.
 * Re-run on every activation so the runtime path stays current.
 */
export function writeLauncher(scriptSource: string, runtime: string): string {
  const dir = hooksDir();
  fs.mkdirSync(dir, { recursive: true });
  const script = path.join(dir, "handoff-hook.js");
  fs.copyFileSync(scriptSource, script);
  if (process.platform === "win32") {
    const launcher = path.join(dir, `${TAG}.cmd`);
    fs.writeFileSync(
      launcher,
      [
        "@echo off",
        `where node >nul 2>nul && (node "${script}" %*) || (set ELECTRON_RUN_AS_NODE=1& "${runtime}" "${script}" %*)`,
        "",
      ].join("\r\n")
    );
    return launcher;
  }
  const launcher = path.join(dir, `${TAG}.sh`);
  fs.writeFileSync(
    launcher,
    [
      "#!/bin/sh",
      "# AgentPool handoff hook launcher (regenerated by the extension).",
      `if command -v node >/dev/null 2>&1; then exec node ${sh(script)} "$@"; fi`,
      `ELECTRON_RUN_AS_NODE=1 exec ${sh(runtime)} ${sh(script)} "$@"`,
      "",
    ].join("\n"),
    { mode: 0o755 }
  );
  fs.chmodSync(launcher, 0o755);
  return launcher;
}

/** The hook command for one mode, quoted for the shell Claude Code runs hooks in. */
export function hookCommand(launcher: string, mode: "stop" | "session-start"): string {
  const p = launcher.replace(/\\/g, "/");
  return `${/\s/.test(p) ? `"${p}"` : p} ${mode}`;
}

type HookEntry = { matcher?: string; hooks: Array<{ type: string; command: string; timeout?: number }> };
type Settings = { hooks?: Record<string, HookEntry[]>; [key: string]: unknown };

/** Adds (or refreshes) AgentPool's Stop and SessionStart hooks; other hooks stay untouched. */
export function installHooks(settingsFile: string, launcher: string): void {
  const settings = readSettings(settingsFile);
  const hooks = (settings.hooks ??= {});
  const add = (event: string, mode: "stop" | "session-start") => {
    hooks[event] = (hooks[event] ?? []).filter((e) => !isOurs(e));
    hooks[event].push({ hooks: [{ type: "command", command: hookCommand(launcher, mode), timeout: 10 }] });
  };
  add("Stop", "stop");
  add("SessionStart", "session-start");
  writeSettings(settingsFile, settings);
}

export function uninstallHooks(settingsFile: string): void {
  if (!fs.existsSync(settingsFile)) {
    return;
  }
  const settings = readSettings(settingsFile);
  for (const [event, entries] of Object.entries(settings.hooks ?? {})) {
    const kept = entries.filter((e) => !isOurs(e));
    if (kept.length) {
      settings.hooks![event] = kept;
    } else {
      delete settings.hooks![event];
    }
  }
  writeSettings(settingsFile, settings);
}

export function hooksInstalled(settingsFile: string): boolean {
  const hooks = readSettings(settingsFile).hooks ?? {};
  return (hooks.Stop ?? []).some(isOurs) && (hooks.SessionStart ?? []).some(isOurs);
}

function isOurs(entry: HookEntry): boolean {
  return entry.hooks?.some((h) => h.command?.includes(TAG));
}

function readSettings(file: string): Settings {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8")) as Settings;
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === "ENOENT") {
      return {};
    }
    // Never rewrite a settings file AgentPool could not parse: that would drop the person's settings.
    throw new Error(`Cannot read ${file}: ${(e as Error).message}`);
  }
}

function writeSettings(file: string, settings: Settings): void {
  // Write through a symlink (the VS Code slot links settings.json to ~/.claude).
  const target = fs.existsSync(file) ? fs.realpathSync(file) : file;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const tmp = `${target}.agent-pool.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(settings, null, 2) + "\n");
  replaceFile(tmp, target);
}

function sh(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}
